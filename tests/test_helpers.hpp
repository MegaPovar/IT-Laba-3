#pragma once

inline int SquareTestInt(int value) {
    return value * value;
}

inline bool IsEvenTestInt(int value) {
    return value % 2 == 0;
}

inline int SumTestInt(int sum, int value) {
    return sum + value;
}

inline int AddIndexTestInt(int value, int index) {
    return value + index;
}
